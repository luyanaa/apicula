"""Synthesise an XPN-style slice program from what a packer knows.

The vendor writes one program per slice (``SLICE_A..D``) describing the LUT
functions, the used register banks and the clock/reset/enable muxes.  The
bitstream is generated by evaluating the BFD equations against that program, so
a writer driven by nextpnr needs to produce the same fields.

The recipe below is measured from vendor runs, not guessed:

=================  ==========================================================
feature            fields the vendor emits (beyond ``MODE:LOGIC``)
=================  ==========================================================
LUT only           ``K0::H0=.. F0:F``
DFF from LUT       ``REG0:::REGSET=RESET,CLKDELAY=DEL0:SD=1 Q0:Q GSR:ENABLED``
                   ``CLKMUX:CLK:::0=0,CLK=#SIG CEMUX:1:::1=1,CE=#SIG``
                   ``SRMODE:ASYNC LSRONMUX:0 REGMODE:FF``
DFF from routing   as above but ``SD=0`` and ``M0MUX:M0``
async reset        the above plus ``LSRMUX:LSR:::0=0,LSR=#SIG`` and
                   ``LSRONMUX:LSRMUX`` (``SRMODE`` stays ``ASYNC``)
sync reset + CE    ``LSRMUX`` as above with ``SRMODE:LSR_OVER_CE``
=================  ==========================================================

``SD`` says where the D input comes from: 1 = the slice LUT (F -> DI is a
hardwired slice connection, not a fuse), 0 = the routed ``M`` site input.
The ``OFX -> DI`` fuses exist in the BFD but the vendor leaves them at 0.

Normalised counters against two vendor XPN exports (``SL2-12E_dff_lut.xpn``,
``SL2-12E_dff_route.xpn``) are in ``tests/test_xist_sliceprog.py``.
"""

from __future__ import annotations

from dataclasses import dataclass, field

_SD_ROUTE = 0
_SD_LUT = 1


@dataclass
class SliceFacts:
    """What is instantiated in one slice, in site-local bank indices (0/1)."""

    luts: tuple[int, ...] = ()
    dffs: tuple[int, ...] = ()
    functions: dict[int, str] = field(default_factory=dict)
    sd_from_lut: bool = True
    ce: bool = False
    reset: bool = False
    reset_is_async: bool = True

    def __post_init__(self):
        for bank in self.dffs:
            if bank not in (0, 1):
                raise ValueError(f"DFF bank {bank} outside 0/1")


def _lut_term(bank: int) -> str:
    return f"K{bank}::H{bank}" if bank in (0, 1) else ""


def slice_program(facts: SliceFacts) -> str:
    """The vendor-shaped program string for a slice."""
    parts: list[str] = ["MODE:LOGIC"]
    for bank in facts.luts:
        func = facts.functions.get(bank)
        parts.append(f"K{bank}::H{bank}={func}" if func else _lut_term(bank))
    for bank in facts.dffs:
        parts.append(f"REG{bank}:::REGSET=RESET,CLKDELAY=DEL0:"
                     f"SD={_SD_LUT if facts.sd_from_lut else _SD_ROUTE}")
    for bank in facts.dffs:
        parts.append(f"Q{bank}:Q")
    for bank in facts.luts:
        parts.append(f"F{bank}:F")
    if not facts.dffs:
        return " ".join(parts)

    parts.append("GSR:ENABLED")
    parts.append("CLKMUX:CLK:::0=0,CLK=#SIG")
    parts.append("CEMUX:1:::1=1,CE=#SIG")
    if facts.reset:
        parts.append("LSRMUX:LSR:::0=0,LSR=#SIG")
        parts.append("LSRONMUX:LSRMUX")
    else:
        parts.append("LSRONMUX:0")
    if facts.reset:
        parts.append("SRMODE:ASYNC" if facts.reset_is_async else "SRMODE:LSR_OVER_CE")
    else:
        parts.append("SRMODE:ASYNC")
    if not facts.sd_from_lut and 0 in facts.dffs:
        parts.append("M0MUX:M0")
        if 1 in facts.dffs:
            parts.append("M1MUX:M1")
    parts.append("REGMODE:FF")
    return " ".join(parts)
